local root=arg[1] or "."
package.path=root.."/?.lua;"..root.."/focusreader.koplugin/?.lua;"..package.path
local H=require("tests/harness")
local D=require("focusreader/line_detector")
local N=require("focusreader/navigation")
local S=require("focusreader/settings")
local V=require("focusreader/focusview")
local function lines(n)
    local result={}
    for i=1,n do result[i]={x=10,y=i*30,w=150,h=20} end
    return result
end
H.test("padrões independentes: duas linhas, passo um, combinado",function()
    local s=S.normalize({}); H.eq(s.lines,2); H.eq(s.step,1); H.eq(s.mode,"combined"); H.eq(s.enabled,false)
end)
H.test("configurações inválidas e limites são saneados",function()
    local s=S.normalize({lines=999,step=-2,intensity=0/0,style="invalid",visible="yes",mode={},thickness=math.huge})
    H.eq(s.lines,5); H.eq(s.step,1); H.eq(s.intensity,18); H.eq(s.style,"soft"); H.eq(s.visible,true); H.eq(s.thickness,2)
end)
H.test("fragmentos fora de ordem e duplicados formam uma linha visual",function()
    local b={{x=80,y=40,w=40,h=20},{x=10,y=10,w=30,h=20},{x=10,y=40,w=30,h=20},{x=10,y=40,w=30,h=20}}
    local found=D.normalize(b,{x=0,y=0,w=200,h=200})
    H.eq(#found,2); H.eq(found[2].w,110)
end)
H.test("parágrafo curto seguido por recuo maior não pula linha",function()
    local found=D.normalize({{x=10,y=10,w=8,h=20},{x=80,y=40,w=100,h=20}},{x=0,y=0,w=200,h=200})
    H.eq(#found,2); H.eq(found[2].y,40)
end)
H.test("caixas inválidas são descartadas e caixas externas recortadas",function()
    local found=D.normalize({{x=-5,y=-5,w=20,h=20},{x=1,y=1,w=0,h=2},{x=0/0,y=1,w=2,h=2},{x=1,y=300,w=10,h=10}},
        {x=0,y=0,w=100,h=100})
    H.eq(#found,1); H.eq(found[1].x,0); H.eq(found[1].h,15)
end)
H.test("capitular alta é recusada sem inventar ou fundir linhas",function()
    local ok=pcall(D.normalize,{{x=10,y=10,w=10,h=60},{x=25,y=10,w=100,h=20},{x=25,y=40,w=100,h=20}},
        {x=0,y=0,w=200,h=200})
    H.eq(ok,false)
end)
H.test("altura real da janela inclui alturas e espaçamentos variáveis",function()
    local nav=N.new(); nav:setLines({{x=10,y=20,w=100,h=40},{x=30,y=90,w=80,h=18}},2)
    H.eq(nav:region().h,88); H.eq(nav:region().w,100)
end)
H.test("número destacado não altera o passo",function()
    local nav=N.new(); nav:setLines(lines(10),3)
    H.eq(nav:move(1,1),"line"); H.eq(nav.index,2); H.eq(nav:region().h,80)
end)
H.test("passo maior para no último bloco antes de pedir página",function()
    local nav=N.new(); nav:setLines(lines(8),2,6)
    H.eq(nav:move(1,3),"line"); H.eq(nav.index,7)
    H.eq(nav:move(1,3),"page"); H.eq(nav.index,7)
end)
H.test("retrocesso equivalente e página com menos linhas",function()
    local nav=N.new(); nav:setLines(lines(2),5)
    H.eq(nav.index,1); H.eq(nav:move(-1,1),"page"); H.eq(nav:region().h,50)
end)
H.test("página vazia não pede virada recursiva",function()
    local nav=N.new(); nav:setLines({},2); H.eq(nav:move(1,1),"empty"); H.eq(nav:region(),nil)
end)
H.test("arraste ajusta à linha mais próxima respeitando o último bloco",function()
    local nav=N.new(); nav:setLines(lines(5),2)
    H.eq(nav:nearest(70),2); H.eq(nav:nearest(999),4); H.eq(nav:nearest(-200),1)
end)
H.test("régua respeita limites do conteúdo mesmo com margens adicionais",function()
    local rect=V.rect({x=4,y=3,w=94,h=94},{x=0,y=0,w=100,h=100},S.normalize({horizontal_padding=24,vertical_padding=12}),function(n) return n end)
    H.eq(rect.x,0); H.eq(rect.y,0); H.eq(rect.w,100); H.eq(rect.h,100)
end)
H.test("área de refresh cobre posição antiga e nova",function()
    local rect=V.union({x=10,y=20,w=100,h=20},{x=20,y=65,w=100,h=15})
    H.eq(rect.x,10); H.eq(rect.y,20); H.eq(rect.w,110); H.eq(rect.h,60)
end)
H.test("preenchimento usa escurecimento preservando glifos, sem pintura opaca",function()
    local calls={}
    local bb={darkenRect=function(_,...) calls[#calls+1]={...} end}
    V.paint(bb,{x=1,y=2,w=50,h=20},S.normalize({style="soft"}),function(n) return n end)
    H.eq(#calls,1); H.eq(calls[1][5],0.18)
end)
H.finish()
